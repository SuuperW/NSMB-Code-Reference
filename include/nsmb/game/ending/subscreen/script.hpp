	template<size_t N>
	class StringHelper {

	public:

		static constexpr size_t Size = N;

		template<class T> requires(std::is_convertible_v<T, wchar_t>)
		consteval StringHelper(const T (&str)[N]) {
			for (size_t i = 0; i < N; i++) {
				data[i] = charConv(str[i]);
			}
		}

		consteval operator const CharT*() const {
			return data;
		}

		CharT data[N];

	};


